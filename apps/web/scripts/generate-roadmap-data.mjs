import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const appRoot = resolve(scriptDirectory, "..");
const sourcePath = resolve(appRoot, "..", "..", "docs", "PILA_SPRINT_BLUEPRINT.md");
const outputPath = resolve(appRoot, "src", "data", "roadmap.generated.ts");
const source = readFileSync(sourcePath, "utf8");

const phases = [];
let currentPhase = null;
let currentSprint = null;

for (const rawLine of source.split(/\r?\n/)) {
  const line = rawLine.trim();
  const phaseMatch = line.match(/^# Phase (\d+) - (.+)$/);
  const sprintMatch = line.match(/^## Sprint (\d+) - (.+)$/);
  const featureMatch = line.match(/^\| ([A-Z]+-\d+) \| (.+) \| ([3-5]) \| (.+) \|$/);
  const objectiveMatch = line.match(/^\*\*Objective:\*\* (.+)$/);
  const totalMatch = line.match(/^\*\*Sprint total: (\d+) points\*\*$/);
  const deliverableMatch = line.match(/^\*\*Sprint deliverable:\*\* (.+)$/);

  if (phaseMatch) {
    currentPhase = {
      number: Number(phaseMatch[1]),
      title: phaseMatch[2],
      sprints: [],
    };
    phases.push(currentPhase);
    currentSprint = null;
    continue;
  }

  if (sprintMatch && currentPhase) {
    currentSprint = {
      number: Number(sprintMatch[1]),
      title: sprintMatch[2],
      objective: "",
      totalPoints: 0,
      deliverable: "",
      features: [],
    };
    currentPhase.sprints.push(currentSprint);
    continue;
  }

  if (objectiveMatch && currentSprint) {
    currentSprint.objective = objectiveMatch[1];
    continue;
  }

  if (featureMatch && currentSprint) {
    currentSprint.features.push({
      id: featureMatch[1],
      title: featureMatch[2],
      points: Number(featureMatch[3]),
      acceptanceCriteria: featureMatch[4],
    });
    continue;
  }

  if (totalMatch && currentSprint) {
    currentSprint.totalPoints = Number(totalMatch[1]);
    continue;
  }

  if (deliverableMatch && currentSprint) {
    currentSprint.deliverable = deliverableMatch[1];
  }
}

const featureCount = phases.reduce(
  (phaseTotal, phase) =>
    phaseTotal +
    phase.sprints.reduce((sprintTotal, sprint) => sprintTotal + sprint.features.length, 0),
  0,
);

if (phases.length === 0 || featureCount === 0) {
  throw new Error(`The roadmap could not be parsed from ${sourcePath}`);
}

const generated = `/* This file is generated by scripts/generate-roadmap-data.mjs. */
/* Edit docs/PILA_SPRINT_BLUEPRINT.md, then run pnpm roadmap:sync. */

export type RoadmapFeature = {
  id: string;
  title: string;
  points: number;
  acceptanceCriteria: string;
};

export type RoadmapSprint = {
  number: number;
  title: string;
  objective: string;
  totalPoints: number;
  deliverable: string;
  features: RoadmapFeature[];
};

export type RoadmapPhase = {
  number: number;
  title: string;
  sprints: RoadmapSprint[];
};

export const roadmap: RoadmapPhase[] = ${JSON.stringify(phases, null, 2)};
`;

writeFileSync(outputPath, generated, "utf8");
console.log(`Generated ${featureCount} roadmap features at ${outputPath}`);
